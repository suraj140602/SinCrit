export const compileBackendWizardContext = (schema) => {
  const tables = schema.appConfig?.dbTables || [];
  const backendType = schema.backendProvider || 'supabase';

  const tableSchemas = tables
    .map((t) => {
      const cols = (t.columns || []).map((c) => `${c.name} ${mapType(c.type)}`).join(', ');
      return `Table "${t.name}": id UUID PK, created_at TIMESTAMPTZ, ${cols}`;
    })
    .join('\n');

  return `
═══════════════════════════════════════════════════════════
BACKEND ARCHITECT MODE — STEP-BY-STEP SETUP WIZARD
═══════════════════════════════════════════════════════════

The user is setting up their backend. Guide them through these exact steps:

STEP 1 — GENERATE SQL SCHEMA
  The following tables are defined in their visual schema:
  ${tableSchemas || '(no tables defined — ask the user what data they want to store)'}

  Generate the complete CREATE TABLE SQL with:
    - UUID primary keys using gen_random_uuid()
    - created_at TIMESTAMPTZ DEFAULT NOW()
    - Row Level Security (RLS) enabled on all tables
    - A read policy: FOR SELECT USING (true)
    - A write policy: FOR INSERT TO authenticated WITH CHECK (true)

STEP 2 — EXPLAIN WHERE TO RUN IT
  Tell the user to:
  1. Open their Supabase dashboard → SQL Editor
  2. Paste the generated SQL
  3. Click "Run"
  4. Screenshot the green ✓ success message

STEP 3 — BIND TO VISUAL CANVAS
  After the SQL runs, show them how to bind a ListView widget to the table:
  \`\`\`dart
  // In the ListView's FutureBuilder, use:
  future: Supabase.instance.client
      .from('${tables[0]?.name || 'your_table'}')
      .select()
      .order('created_at', ascending: false),
  \`\`\`

STEP 4 — TEST THE CONNECTION
  Generate a simple FutureBuilder snippet that fetches one row and prints it.
  This lets the user confirm the connection works before building the full UI.

OUTPUT FORMAT FOR WIZARD:
  Return a JSON object:
  {
    "sql": "complete SQL string",
    "explanation": "friendly plain-English explanation of what the SQL does",
    "bindingCode": "Dart FutureBuilder snippet",
    "nextStep": "what the user should do next"
  }
═══════════════════════════════════════════════════════════`;
};

// Helper for SQL type mapping
const mapType = (t) => {
  const map = { text: 'TEXT', numeric: 'NUMERIC', boolean: 'BOOLEAN', uuid: 'UUID', timestamp: 'TIMESTAMPTZ' };
  return map[t] || 'TEXT';
};

