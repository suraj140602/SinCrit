/**
 * hexToArgb — converts #RRGGBB to Flutter's 0xFFRRGGBB notation.
 * Handles both shorthand (#FFF) and full (#FFFFFF) hex codes.
 */
const hexToArgb = (hex) => {
  if (!hex) return '0xFF050609';
  const clean = hex.replace('#', '').trim();
  if (clean.length === 3) {
    const r = clean[0] + clean[0];
    const g = clean[1] + clean[1];
    const b = clean[2] + clean[2];
    return `0xFF${r}${g}${b}`.toUpperCase();
  }
  return `0xFF${clean.slice(0, 6)}`.toUpperCase();
};

/**
 * detectThemeMode — inspects the background color luminance to determine
 * whether the schema is using a dark or light theme.
 */
const detectThemeMode = (bgHex) => {
  if (!bgHex) return 'dark';
  const clean = bgHex.replace('#', '');
  const r = parseInt(clean.slice(0, 2), 16) || 0;
  const g = parseInt(clean.slice(2, 4), 16) || 0;
  const b = parseInt(clean.slice(4, 6), 16) || 0;
  // Relative luminance
  const luminance = (0.299 * r + 0.587 * g + 0.114 * b) / 255;
  return luminance > 0.5 ? 'light' : 'dark';
};

